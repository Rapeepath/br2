import type { Market, Model } from '../lib/types'
import enJson from './en.json'
import marketJson from './market.json'
import modelsJson from './models.json'

/**
 * An extra photo (or a video clip with its poster) of a model from Wikimedia Commons. `src`/`srcSmall` are the
 * local 1600px / 640px JPEGs (the poster for a video); `video.url` is the clip on upload.wikimedia.org, never
 * autoplayed, best started at `video.start` seconds where the model appears.
 */
export interface GalleryItem {
  kind: 'image' | 'video'
  src: string
  srcSmall: string
  page: string
  author: string
  license: string
  /** Thai alt text; the English one is en.records[id].gallery[i].alt */
  alt: string
  focus?: string
  zoom?: number
  video?: { url: string; duration: number; start: number }
}

export type ModelWithGallery = Model & { gallery: GalleryItem[] }

/** English for one model: the same keys as the Thai record, arrays item for item, null where the Thai is null. */
export interface ModelEn {
  segment: string
  originCountry: string
  tagline: string
  summary: string
  background: string
  availabilityNote: string
  distributor: string
  /** Same order and names as Model.trims */
  trims: { name: string; hand: string | null; compute: string | null }[]
  sensors: string[]
  charging: { note: string | null }
  software: { sdk: string | null; ai: string | null }
  warranty: { robot: string; battery: string | null; note: string | null }
  safety: { features: string[]; certifications: string[] }
  useCases: string[]
  highlights: string[]
  pros: string[]
  cons: string[]
  idealFor: string[]
  considerations: string[]
  funFact: string | null
  priceNote: string | null
  /** Same order as the model's gallery */
  gallery: { alt: string }[]
}

/** English for the market file's text; every array lines up with the Thai one (shipments largest first). */
export interface MarketEn {
  fx: { note: string | null }
  marketContext: string
  shipments: { brand: string; period: string; note: string | null }[]
  priceFactors: string[]
  buyerChecklist: { title: string; detail: string }[]
  setup: { steps: { title: string; detail: string }[]; costs: { item: string }[] }
  electricity: { label: string; unit: string; note: string | null }[]
  ownershipCost: { yearly: { item: string }[]; oneTime: { item: string }[] }
  sellers: { name: string; detail: string }[]
  notForSale: { name: string; status: string }[]
  incentives: string[]
  legalNotes: string[]
}

export interface EnContent {
  records: Record<string, ModelEn>
  market: MarketEn
}

// Generated by `npm run data` from the research notes; validated in data.test.ts.
export const models = modelsJson as unknown as ModelWithGallery[]
export const market = marketJson as unknown as Market
export const en = enJson as unknown as EnContent

const byId = new Map(models.map((m) => [m.id, m]))

export const getModel = (id: string | undefined): ModelWithGallery | undefined => (id ? byId.get(id) : undefined)

export const getModelEn = (id: string | undefined): ModelEn | undefined => (id ? en.records[id] : undefined)

export const modelIds = models.map((m) => m.id)
